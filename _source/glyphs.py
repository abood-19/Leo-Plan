def star_pts(cx,cy,r):
    pts=[]
    for i in range(10):
        rr=r if i%2==0 else r*.42; a=-math.pi/2+i*math.pi/5
        pts.append((cx+rr*math.cos(a),cy+rr*math.sin(a)))
    return pts
